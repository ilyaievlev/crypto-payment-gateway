// Package memzero предоставляет очистку байтовых срезов с чувствительными данными.
package memzero

import "runtime"

// Bytes перезаписывает b нулями и удерживает срез живым до завершения очистки.
// Функция не может очистить копии, созданные компилятором, runtime или сторонней
// библиотекой, поэтому предоставляет только максимально возможную защиту в Go.
//
//go:noinline
func Bytes(b []byte) {
	clear(b)
	runtime.KeepAlive(b)
}
